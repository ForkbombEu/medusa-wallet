import { AskarModule } from '@credo-ts/askar'
import { Agent, ConsoleLogger, Kms, LogLevel, type X509Certificate, X509KeyUsage } from '@credo-ts/core'
import { agentDependencies } from '@credo-ts/node'
import { askarNodeJS } from '@openwallet-foundation/askar-nodejs'

export const ISSUER_URL = 'https://issuer.medusa.test'
export const PID_VCT = 'urn:eudi:pid:1'
export const PID_DOCTYPE = 'eu.europa.ec.eudi.pid.1'

/**
 * A throwaway Credo agent that signs SD-JWT VC and mdoc credentials, so core
 * tests can exercise storage and decoding without a network issuer.
 */
export class TestIssuer {
  private constructor(
    private readonly agent: Agent,
    private readonly certificate: X509Certificate,
  ) {}

  static async create(): Promise<TestIssuer> {
    const agent = new Agent({
      config: { logger: new ConsoleLogger(LogLevel.Off) },
      dependencies: agentDependencies,
      modules: {
        askar: new AskarModule({
          askar: askarNodeJS,
          store: {
            id: `issuer-${crypto.randomUUID()}`,
            key: 'issuer',
            database: { type: 'sqlite', config: { inMemory: true } },
          },
        }),
      },
    })
    await agent.initialize()

    const { publicJwk } = await agent.kms.createKey({ type: { kty: 'EC', crv: 'P-256' } })
    const issuerKey = Kms.PublicJwk.fromPublicJwk(publicJwk)
    const certificate = await agent.x509.createCertificate({
      authorityKey: issuerKey,
      issuer: { commonName: 'Medusa Test Issuer', countryName: 'NL' },
      extensions: {
        subjectAlternativeName: { name: [{ type: 'url', value: ISSUER_URL }] },
        keyUsage: { usages: [X509KeyUsage.DigitalSignature] },
      },
    })
    return new TestIssuer(agent, certificate)
  }

  /** A holder key generated by the issuer agent; good enough for storage tests. */
  private async holderKey() {
    const { publicJwk } = await this.agent.kms.createKey({ type: { kty: 'EC', crv: 'P-256' } })
    return Kms.PublicJwk.fromPublicJwk(publicJwk)
  }

  async sdJwtVc(claims: Record<string, unknown> = { given_name: 'Ada', family_name: 'Lovelace' }): Promise<string> {
    const { compact } = await this.agent.sdJwtVc.sign({
      issuer: { method: 'x5c', x5c: [this.certificate], issuer: ISSUER_URL },
      holder: { method: 'jwk', jwk: await this.holderKey() },
      payload: { vct: PID_VCT, iat: 1_700_000_000, exp: 2_000_000_000, ...claims },
      disclosureFrame: { _sd: Object.keys(claims) },
    })
    return compact
  }

  async mdoc(claims: Record<string, unknown> = { given_name: 'Ada', family_name: 'Lovelace' }): Promise<string> {
    const mdoc = await this.agent.mdoc.sign({
      docType: PID_DOCTYPE,
      holderKey: await this.holderKey(),
      issuerCertificate: this.certificate,
      namespaces: { [PID_DOCTYPE]: claims },
      validityInfo: {
        signed: new Date('2026-01-01T00:00:00Z'),
        validFrom: new Date('2026-01-01T00:00:00Z'),
        validUntil: new Date('2036-01-01T00:00:00Z'),
      },
    })
    return mdoc.base64Url
  }

  async close(): Promise<void> {
    await this.agent.shutdown()
  }
}
